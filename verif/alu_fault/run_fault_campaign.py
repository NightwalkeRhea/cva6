#!/usr/bin/env python3

import argparse
import csv
import re
import subprocess
import sys
from pathlib import Path


RESULT_MISMATCH_RE = re.compile(
    r"RESULT_MISMATCH "
    r"row=(?P<row>\d+) "
    r"cycle=(?P<cycle>\d+) "
    r"alu=(?P<alu>\d+) "
    r"op=(?P<operation>\d+)"
)

BRANCH_MISMATCH_RE = re.compile(
    r"BRANCH_MISMATCH "
    r"row=(?P<row>\d+) "
    r"cycle=(?P<cycle>\d+) "
    r"op=(?P<operation>\d+)"
)

RESULT_ERRORS_RE = re.compile(r"Result errors:\s*(\d+)")
BRANCH_ERRORS_RE = re.compile(r"Branch errors:\s*(\d+)")
TRANSACTIONS_RE = re.compile(r"Transactions:\s*(\d+)")
MODE_RE = re.compile(r"-mode\s+(\S+)")


def parse_arguments():
    """Collect frozen netlist, fault list, traces, tools, and output paths."""
    parser = argparse.ArgumentParser(
        description="Generate ALU mutants and replay CVA6 ALU traces."
    )

    parser.add_argument(
        "--fault-list",
        required=True,
        type=Path,
        help="Yosys mutation list generated by mutate -list.",
    )

    parser.add_argument(
        "--first",
        type=int,
        default=0,
        help="Zero-based index of the first mutation.",
    )

    parser.add_argument(
        "--count",
        type=int,
        required=True,
        help="Number of mutations to process.",
    )

    parser.add_argument(
        "--traces",
        required=True,
        type=Path,
        help="Directory containing ALU CSV traces.",
    )

    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="Campaign output directory.",
    )

    parser.add_argument(
        "--timeout",
        type=int,
        default=30,
        help="Replay timeout in seconds.",
    )

    return parser.parse_args()


def absolute_path(path, repository):
    """Make paths stable because generated build commands change directories."""
    if path.is_absolute():
        return path.resolve()

    return (repository / path).resolve()


def extract_integer(pattern, text):
    """Read one numeric testbench result or return no value when absent."""
    match = pattern.search(text)

    if match is None:
        return ""

    return int(match.group(1))


def write_infrastructure_rows(
    writer,
    csv_file,
    fault_id,
    mode,
    mutation,
    traces,
    stage,
    message,
):
    """Record every skipped trace as an infrastructure failure, never coverage."""
    for trace in traces:
        trace_name = trace.stem
        program, alu_name = trace_name.rsplit(".", 1)

        writer.writerow(
            {
                "fault_id": fault_id,
                "mode": mode,
                "mutation": mutation,
                "trace": trace_name,
                "program": program,
                "alu_id": alu_name.replace("alu", ""),
                "classification": "INFRASTRUCTURE_ERROR",
                "detected": "",
                "transactions": "",
                "result_errors": "",
                "branch_errors": "",
                "first_failing_transaction": "",
                "first_failing_cycle": "",
                "first_failing_operation": "",
                "error_stage": stage,
                "error_message": message,
            }
        )

    csv_file.flush()


def main():
    """Build every ALU mutant, replay every trace, and classify each pair."""
    args = parse_arguments()

    repository = Path(__file__).resolve().parents[2]

    fault_list_path = absolute_path(args.fault_list, repository)
    trace_directory = absolute_path(args.traces, repository)
    output_directory = absolute_path(args.output, repository)

    golden_json = (
        repository
        / "fi-results/milestone4c-synthesis/alu_cv32a65x_netlist.json"
    )

    replay_testbench = (
        repository / "verif/alu_replay/tb/alu_replay_tb.sv"
    )

    if not fault_list_path.is_file():
        sys.exit(f"Fault list does not exist: {fault_list_path}")

    if not trace_directory.is_dir():
        sys.exit(f"Trace directory does not exist: {trace_directory}")

    if not golden_json.is_file():
        sys.exit(f"Golden JSON netlist does not exist: {golden_json}")

    if not replay_testbench.is_file():
        sys.exit(f"Replay testbench does not exist: {replay_testbench}")

    mutation_lines = [
        line.strip()
        for line in fault_list_path.read_text().splitlines()
        if line.strip()
    ]

    first = args.first
    stop = first + args.count

    if first < 0 or args.count <= 0:
        sys.exit("--first must be nonnegative and --count must be positive")

    if stop > len(mutation_lines):
        sys.exit(
            f"Requested mutations {first} through {stop - 1}, "
            f"but the list contains only {len(mutation_lines)} entries"
        )

    traces = sorted(trace_directory.glob("*.csv"))

    if not traces:
        sys.exit(f"No CSV traces found in: {trace_directory}")

    yosys_datdir = Path(
        subprocess.check_output(
            ["yosys-config", "--datdir"],
            text=True,
        ).strip()
    )

    simcells = yosys_datdir / "simcells.v"

    if not simcells.is_file():
        sys.exit(f"Yosys simulation cells do not exist: {simcells}")

    scripts_directory = output_directory / "yosys-scripts"
    netlists_directory = output_directory / "netlists"
    builds_directory = output_directory / "builds"
    logs_directory = output_directory / "logs"

    scripts_directory.mkdir(parents=True, exist_ok=True)
    netlists_directory.mkdir(parents=True, exist_ok=True)
    builds_directory.mkdir(parents=True, exist_ok=True)
    logs_directory.mkdir(parents=True, exist_ok=True)

    results_path = output_directory / "fault-results.csv"

    fieldnames = [
        "fault_id",
        "mode",
        "mutation",
        "trace",
        "program",
        "alu_id",
        "classification",
        "detected",
        "transactions",
        "result_errors",
        "branch_errors",
        "first_failing_transaction",
        "first_failing_cycle",
        "first_failing_operation",
        "error_stage",
        "error_message",
    ]

    with results_path.open("w", newline="") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=fieldnames)
        writer.writeheader()
        csv_file.flush()

        for fault_index in range(first, stop):
            fault_id = f"{fault_index:03d}"
            mutation = mutation_lines[fault_index]

            mode_match = MODE_RE.search(mutation)
            mode = mode_match.group(1) if mode_match else "unknown"

            print(
                f"[fault {fault_id}] generating mode={mode}",
                flush=True,
            )

            yosys_script = scripts_directory / f"fault_{fault_id}.ys"
            mutant_netlist = netlists_directory / f"fault_{fault_id}.v"
            generation_log = logs_directory / f"fault_{fault_id}.generation.log"

            build_directory = builds_directory / f"fault_{fault_id}"
            build_directory.mkdir(parents=True, exist_ok=True)

            mutant_binary = build_directory / f"alu_replay_fault_{fault_id}"
            build_log = logs_directory / f"fault_{fault_id}.build.log"

            mutant_netlist.unlink(missing_ok=True)
            mutant_binary.unlink(missing_ok=True)

            yosys_script.write_text(
                "\n".join(
                    [
                        f'read_json "{golden_json}"',
                        "hierarchy -check -top alu_cv32a65x_wrapper",
                        mutation,
                        "opt_clean",
                        "check",
                        f'write_verilog -noattr "{mutant_netlist}"',
                        "",
                    ]
                )
            )

            with generation_log.open("w") as log_file:
                generation_result = subprocess.run(
                    [
                        "yosys",
                        "-Q",
                        str(yosys_script),
                    ],
                    cwd=repository,
                    stdout=log_file,
                    stderr=subprocess.STDOUT,
                    text=True,
                )

            if generation_result.returncode != 0 or not mutant_netlist.is_file():
                message = (
                    f"Yosys returned {generation_result.returncode}; "
                    f"see {generation_log}"
                )

                print(f"[fault {fault_id}] generation failed", flush=True)

                write_infrastructure_rows(
                    writer,
                    csv_file,
                    fault_id,
                    mode,
                    mutation,
                    traces,
                    "generation",
                    message,
                )
                continue

            print(f"[fault {fault_id}] compiling", flush=True)

            verilator_command = [
                "verilator",
                "--binary",
                "--timing",
                "-Wno-fatal",
                "--top-module",
                "alu_replay_tb",
                "--Mdir",
                str(build_directory),
                "-o",
                mutant_binary.name,
                str(simcells),
                str(mutant_netlist),
                str(replay_testbench),
            ]

            with build_log.open("w") as log_file:
                build_result = subprocess.run(
                    verilator_command,
                    cwd=repository,
                    stdout=log_file,
                    stderr=subprocess.STDOUT,
                    text=True,
                )

            if build_result.returncode != 0 or not mutant_binary.is_file():
                message = (
                    f"Verilator returned {build_result.returncode}; "
                    f"see {build_log}"
                )

                print(f"[fault {fault_id}] compilation failed", flush=True)

                write_infrastructure_rows(
                    writer,
                    csv_file,
                    fault_id,
                    mode,
                    mutation,
                    traces,
                    "compilation",
                    message,
                )
                continue

            for trace in traces:
                trace_name = trace.stem
                program, alu_name = trace_name.rsplit(".", 1)
                alu_id = alu_name.replace("alu", "")

                replay_log = (
                    logs_directory / f"fault_{fault_id}.{trace_name}.log"
                )

                print(
                    f"[fault {fault_id}] replaying {trace_name}",
                    flush=True,
                )

                try:
                    replay_result = subprocess.run(
                        [
                            str(mutant_binary),
                            "+fault_campaign",
                            f"+trace_file={trace}",
                        ],
                        cwd=repository,
                        stdout=subprocess.PIPE,
                        stderr=subprocess.STDOUT,
                        text=True,
                        timeout=args.timeout,
                    )

                    replay_output = replay_result.stdout
                    replay_log.write_text(replay_output)

                except subprocess.TimeoutExpired as error:
                    replay_output = error.stdout or ""

                    if isinstance(replay_output, bytes):
                        replay_output = replay_output.decode(
                            errors="replace"
                        )

                    replay_log.write_text(replay_output)

                    writer.writerow(
                        {
                            "fault_id": fault_id,
                            "mode": mode,
                            "mutation": mutation,
                            "trace": trace_name,
                            "program": program,
                            "alu_id": alu_id,
                            "classification": "INFRASTRUCTURE_ERROR",
                            "detected": "",
                            "transactions": "",
                            "result_errors": "",
                            "branch_errors": "",
                            "first_failing_transaction": "",
                            "first_failing_cycle": "",
                            "first_failing_operation": "",
                            "error_stage": "replay_timeout",
                            "error_message": (
                                f"Replay exceeded {args.timeout} seconds"
                            ),
                        }
                    )
                    csv_file.flush()
                    continue

                detected_marker = "*** FAULT DETECTED ***"
                undetected_marker = "*** FAULT NOT DETECTED ***"

                if detected_marker in replay_output:
                    classification = "DETECTED"
                    detected = 1
                elif undetected_marker in replay_output:
                    classification = "NOT_DETECTED"
                    detected = 0
                else:
                    classification = "INFRASTRUCTURE_ERROR"
                    detected = ""

                transactions = extract_integer(
                    TRANSACTIONS_RE,
                    replay_output,
                )
                result_errors = extract_integer(
                    RESULT_ERRORS_RE,
                    replay_output,
                )
                branch_errors = extract_integer(
                    BRANCH_ERRORS_RE,
                    replay_output,
                )

                first_mismatch = RESULT_MISMATCH_RE.search(replay_output)

                if first_mismatch is None:
                    first_mismatch = BRANCH_MISMATCH_RE.search(replay_output)

                if first_mismatch is None:
                    first_transaction = ""
                    first_cycle = ""
                    first_operation = ""
                else:
                    first_transaction = first_mismatch.group("row")
                    first_cycle = first_mismatch.group("cycle")
                    first_operation = first_mismatch.group("operation")

                error_stage = ""
                error_message = ""

                if classification == "INFRASTRUCTURE_ERROR":
                    error_stage = "replay"
                    error_message = (
                        f"Simulator returned {replay_result.returncode} "
                        "without a classification marker"
                    )

                writer.writerow(
                    {
                        "fault_id": fault_id,
                        "mode": mode,
                        "mutation": mutation,
                        "trace": trace_name,
                        "program": program,
                        "alu_id": alu_id,
                        "classification": classification,
                        "detected": detected,
                        "transactions": transactions,
                        "result_errors": result_errors,
                        "branch_errors": branch_errors,
                        "first_failing_transaction": first_transaction,
                        "first_failing_cycle": first_cycle,
                        "first_failing_operation": first_operation,
                        "error_stage": error_stage,
                        "error_message": error_message,
                    }
                )
                csv_file.flush()

    print()
    print(f"Wrote campaign results: {results_path}")


if __name__ == "__main__":
    main()
